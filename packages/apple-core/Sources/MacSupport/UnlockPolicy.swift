import Foundation

/// Only extend a one-of-N rule; preserve every pre-existing branch and its order.
public enum UnlockPolicy {
    public static var mechanism: [String: Any] {
        [
            "class": "evaluate-mechanisms", "mechanisms": ["SofaRemoteUnlock:unlock,privileged"],
            "shared": false, "tries": 1
        ]
    }
    public static func extended(_ original: Data) throws -> Data {
        var values = try dictionary(original)
        guard values["class"] as? String == "rule",
            let count = values["k-of-n"] as? NSNumber, CFGetTypeID(count) != CFBooleanGetTypeID(),
            count.doubleValue == 1,
            let rules = values["rule"] as? [String], !rules.isEmpty, rules.count < 16,
            !rules.contains(UnlockPaths.right)
        else { throw UnlockFailure.conflict }
        values["rule"] = [UnlockPaths.right] + rules
        return try data(behavior(values))
    }

    public static func writeDefinition(_ bytes: Data) throws -> [String: Any] {
        try behavior(dictionary(bytes))
    }

    public static func createdBy(_ bytes: Data, identifier: String, requirement: String) throws
        -> Bool
    {
        let values = try dictionary(bytes)
        return values["identifier"] as? String == identifier
            && values["requirement"] as? String == requirement
    }

    public static func matches(_ actual: Data, desired: Data) throws -> Bool {
        try NSDictionary(dictionary: behavior(dictionary(actual)))
            .isEqual(to: behavior(dictionary(desired)))
    }

    public static func sameDefinition(_ left: Data?, _ right: Data?) throws -> Bool {
        guard let left, let right else { return left == nil && right == nil }
        // Compare every field, including owner and modification metadata, while
        // allowing XML/binary serialization and dictionary-key order to differ.
        return try NSDictionary(dictionary: dictionary(left)).isEqual(to: dictionary(right))
    }

    public static func dictionary(_ bytes: Data) throws -> [String: Any] {
        guard bytes.count <= 65_536,
            let value = try PropertyListSerialization.propertyList(from: bytes, format: nil)
                as? [String: Any]
        else { throw UnlockFailure.conflict }
        return value
    }

    public static func data(_ value: [String: Any]) throws -> Data {
        try PropertyListSerialization.data(fromPropertyList: value, format: .xml, options: 0)
    }

    private static func behavior(_ values: [String: Any]) -> [String: Any] {
        var result = values
        for key in ["created", "modified", "version"] { result.removeValue(forKey: key) }
        // Creator metadata is generated by Authorization Services. Freshness
        // checks use the entire recorded readback, including these fields.
        for key in ["identifier", "requirement"] { result.removeValue(forKey: key) }
        return result
    }
}
